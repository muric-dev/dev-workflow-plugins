"""Step 5. usage.json -> what people read.

- LEDGER.md: Markdown tables committed with the project, rewritten on every sync.
- board(): the console view `report` prints, overall, per feature and phase, and per
  kind (work or question) and category.

Both read the same rows from summarize(), so their numbers always agree, and
neither holds data of its own.
"""
from common import REPORT_FILE, write_atomic

BAR_WIDTH = 20


def add_row(rows, key, question, model=None):
    """Add a whole question, or only one of its model entries, to the row at `key`."""
    row = rows.setdefault(key, {"questions": 0, "calls": 0, "read": 0, "write": 0, "input": 0, "output": 0,
                                "usd": 0.0, "active": 0})
    for entry in question["models"] if model is None else [model]:
        row["calls"] += entry["calls"]
        row["input"] += entry["input_tokens"]
        row["output"] += entry["output_tokens"]
        row["read"] += entry["cache_read_tokens"]
        row["write"] += entry["cache_write_5m_tokens"] + entry["cache_write_1h_tokens"]
    row["questions"] += 1
    row["usd"] += question["usd"] if model is None else model["usd"]
    row["active"] += question["active_seconds"] if model is None else 0


def label(question):
    """kind, or kind/category: question, work, question/review."""
    kind = question.get("kind") or "unknown"
    return f"{kind}/{question['category']}" if question.get("category") else kind


def summarize(doc):
    """Rows keyed by feature, by (feature, phase), by (feature, phase, label), by label,
    and by (model, effort)."""
    by_feature, by_phase, by_kind, by_label, by_model = {}, {}, {}, {}, {}
    for question in doc["questions"]:
        add_row(by_feature, question["feature"], question)
        add_row(by_phase, (question["feature"], question["phase"]), question)
        add_row(by_kind, (question["feature"], question["phase"], label(question)), question)
        add_row(by_label, (label(question),), question)
        for model in question["models"]:
            add_row(by_model, (model["model"], model["effort"]), question, model)
    return by_feature, by_phase, by_kind, by_label, by_model


# LEDGER.md


def table(title, labels, rows, with_time):
    head = [*labels, "Input", "Output", "Cache read", "Cache write", "USD (API)"]
    lines = [f"## {title}", "", "| " + " | ".join(head + (["Active"] if with_time else [])) + " |"]
    lines.append("|" + "---|" * len(labels) + "---:|" * (len(head) - len(labels) + int(with_time)))
    for key, row in sorted(rows.items()):
        cells = [*key, f"{row['input']:,}", f"{row['output']:,}", f"{row['read']:,}", f"{row['write']:,}", f"{row['usd']:.2f}"]
        cells += [f"{row['active'] / 60:.1f} min"] if with_time else []
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render(doc):
    _, by_phase, by_kind, _, by_model = summarize(doc)
    totals = doc["totals"]
    return "\n".join([
        "# Usage ledger",
        "",
        "<!-- Generated by usage-ledger. Edits here are overwritten. -->",
        "",
        f"**{totals['usd']:.2f} USD** across {totals['questions']} questions and {totals['calls']} model "
        f"calls, {totals['active_seconds'] / 60:.1f} min active. USD is the API list-price equivalent "
        f"(prices as of {doc['prices']['as_of']}), not an invoice.",
        "",
        *table("By feature and phase", ["Feature", "Phase"], by_phase, True),
        "",
        *table("By kind and category", ["Feature", "Phase", "Kind / category"], by_kind, True),
        "",
        *table("By model", ["Model", "Effort"], by_model, False),
        "",
    ])


def write_report(root, doc):
    path = root / REPORT_FILE
    text = render(doc)
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        write_atomic(path, text)


# Console board


def compact(number):
    for limit, suffix in ((1e9, "B"), (1e6, "M"), (1e3, "K")):
        if number >= limit:
            return f"{number / limit:.1f}{suffix}"
    return str(number)


def duration(seconds):
    hours, minutes = divmod(round(seconds / 60), 60)
    return f"{hours}h {minutes:02d}m" if hours else f"{minutes}m"


def most_expensive_first(rows):
    return sorted(rows.items(), key=lambda item: (-item[1]["usd"], item[0]))


def board_table(title, rows, total_usd, with_time):
    """One line per row: name, a bar of its share of all USD, then the numbers."""
    width = max(len(title), *(len(name) for name, _ in rows))
    head = f"{title:<{width}}  {'':<{BAR_WIDTH}}  {'USD':>8}  {'Share':>5}  {'Questions':>9}  {'Calls':>6}  {'Tokens':>7}"
    lines = [head + (f"  {'Active':>8}" if with_time else "")]
    for name, row in rows:
        share = row["usd"] / total_usd if total_usd else 0
        filled = round(share * BAR_WIDTH)
        tokens = row["input"] + row["output"] + row["read"] + row["write"]
        line = (f"{name:<{width}}  {'█' * filled}{'░' * (BAR_WIDTH - filled)}  {row['usd']:>8.2f}  {share:>5.0%}  "
                f"{row['questions']:>9,}  {row['calls']:>6,}  {compact(tokens):>7}")
        lines.append(line + (f"  {duration(row['active']):>8}" if with_time else ""))
    return lines


def board(doc):
    totals = doc["totals"]
    lines = [
        f"Usage ledger: {totals['usd']:.2f} USD, {totals['questions']} questions, {totals['calls']} calls, "
        f"{duration(totals['active_seconds'])} active",
        f"USD is the API list-price equivalent (prices as of {doc['prices']['as_of']}), not an invoice.",
    ]
    if not doc["questions"]:
        return "\n".join([*lines, "", "No questions recorded yet."])
    by_feature, by_phase, by_kind, by_label, by_model = summarize(doc)
    features = []
    for feature, row in most_expensive_first(by_feature):
        features.append((feature, row))
        phases = {phase: row for (owner, phase), row in by_phase.items() if owner == feature}
        for phase, phase_row in most_expensive_first(phases):
            features.append((f"  {phase}", phase_row))
            kinds = {kind: row for (owner, step, kind), row in by_kind.items() if (owner, step) == (feature, phase)}
            features += [(f"    {kind}", row) for kind, row in most_expensive_first(kinds)]
    labels = [(name, row) for (name,), row in most_expensive_first(by_label)]
    models = [(f"{model} ({effort})", row) for (model, effort), row in most_expensive_first(by_model)]
    return "\n".join([
        *lines,
        "",
        *board_table("Feature / phase / kind", features, totals["usd"], True),
        "",
        *board_table("Kind / category", labels, totals["usd"], True),
        "",
        *board_table("Model (effort)", models, totals["usd"], False),
    ])
